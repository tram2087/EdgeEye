@app.on_event("startup")
async def startup_event():
    init_db()
    seed_demo_data()
    global_engine.sync_zones_from_db()
    # Register default cameras into processor
    for cid in ["BOP-01", "BOP-02", "BOP-03", "CHECKPOST-01"]:
        global_engine.register_camera(cid)
    # Start background alert broadcasting task
    asyncio.create_task(background_alert_broadcast())
    logger.info("EdgeEye AI & Video Analytics System initialized successfully.")

@app.on_event("shutdown")
async def shutdown_event():
    logger.info("Releasing EdgeEye video streams and background workers...")
    global_engine.cleanup()

