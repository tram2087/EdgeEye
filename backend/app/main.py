# Active WebSocket clients
connected_clients: list[WebSocket] = []

@app.websocket("/ws/alerts")
async def websocket_alerts_endpoint(websocket: WebSocket):
    await websocket.accept()
    connected_clients.append(websocket)
    logger.info(f"WebSocket client connected. Total clients: {len(connected_clients)}")
    try:
        # Send recent alerts on initial connect
        for a in global_engine.recent_alerts[:5]:
            await websocket.send_text(json.dumps(a))

        while True:
            # Keep-alive receive
            data = await websocket.receive_text()
            if data == "ping":
                await websocket.send_text("pong")
    except WebSocketDisconnect:
        connected_clients.remove(websocket)
        logger.info("WebSocket client disconnected.")
    except Exception as e:
        if websocket in connected_clients:
            connected_clients.remove(websocket)
        logger.error(f"WebSocket error: {e}")

async def background_alert_broadcast():
    """
    Periodically checks if new alerts were generated by the event engine and broadcasts to WebSockets.
    """
    last_sent_alert_id = 0
    while True:
        try:
            if connected_clients and global_engine.recent_alerts:
                latest = global_engine.recent_alerts[0]
                if latest.get("id") != last_sent_alert_id:
                    last_sent_alert_id = latest.get("id")
                    payload = json.dumps(latest)
                    for ws in list(connected_clients):
                        try:
                            await ws.send_text(payload)
                        except Exception:
                            if ws in connected_clients:
                                connected_clients.remove(ws)
        except Exception as e:
            logger.error(f"Broadcast error: {e}")
        await asyncio.sleep(1.0)

